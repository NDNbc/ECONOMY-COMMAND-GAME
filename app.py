@app.post('/api/start')
def start():
 if not authhost():abort(403)
 with LOCK:
  if GAME['phase']!='lobby':return jsonify(error='Тоглоом эхэлсэн'),409
  names=(request.get_json(silent=True) or {}).get('names',[])
  for i,t in enumerate(TEAMS):
   if i<len(names):t['name']=str(names[i]).strip()[:35] or t['name']
  GAME['phase']='answer';GAME['revision']+=1;save_state()
 return jsonify(public())
@app.post('/api/answer')
def answer():
 t=findteam()
 if not t:return jsonify(error='Багийн QR холбоос хүчингүй эсвэл хуучирсан байна. Шинэ QR код уншуулна уу.'),403
 d=request.get_json(silent=True) or {}
 try: choice=int(d.get('choice'))
 except (ValueError,TypeError):return jsonify(error='Хариулт буруу'),400
 with LOCK:
  if GAME['phase']!='answer':return jsonify(error='Тоглоом эхлээгүй эсвэл дууссан'),409
  r=t.get('round',0)
  evs=DATA[t['year']]['events']
  if r>=len(evs):return jsonify(error='Энэ багийн бүх шийдвэр дууссан'),409
  if choice<0 or choice>=len(evs[r][2]):return jsonify(error='Сонголт буруу'),400
  e=evs[r];c=e[2][choice];before=t['stats'][:]
  t['stats']=[max(0,min(100,x+dx)) for x,dx in zip(before,c[2])]
  entry={'title':e[0],'choice':c[0],'explanation':c[3],'delta':c[2],'before':before,'after':t['stats'][:],'round':r+1}
  t['log'].append(entry)
  t['round']=r+1
  GAME['last']=[{'team':t['name'],'year':t['year'],**entry}]
  if all(x.get('round',0)>=len(DATA[x['year']]['events']) for x in TEAMS):GAME['phase']='finished'
  GAME['revision']+=1;save_state()
 return jsonify({'ok':True,'next_round':t['round'],'finished':t['round']>=len(evs),'state':public()})
